#!/usr/bin/env bash
# Finds pictures in the uploads volume that no product, product gallery or category uses, and deletes them with
# --apply. Replacing a photo in the admin leaves the old file behind; this cleans those up.
#
#   bash scripts/prune-uploads.sh            list only, deletes nothing
#   bash scripts/prune-uploads.sh --apply    delete them (also from the backup mirror, and from BACKUP_REMOTE if set)
#
# Environment (optional):
#   MIN_AGE_MINUTES  only files older than this are touched, so a photo just uploaded in an editor that is not
#                    saved yet is safe (default: 60)
#   BACKUP_DIR       backup folder whose uploads/ mirror is cleaned too (default: data/backups)
#   BACKUP_REMOTE    rclone destination used by scripts/backup.sh, e.g. gdrive:tinphat-backups

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE=(docker compose -f "$ROOT/deploy/compose.yml" --env-file "$ROOT/deploy/.env")
MIN_AGE_MINUTES="${MIN_AGE_MINUTES:-60}"
MIRROR="${BACKUP_DIR:-$ROOT/data/backups}/uploads/images"
APPLY=false
[ "${1:-}" = "--apply" ] && APPLY=true
case "$MIN_AGE_MINUTES" in ''|*[!0-9]*) echo "MIN_AGE_MINUTES must be a whole number" >&2; exit 1 ;; esac

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# every picture the site uses, as a bare file name
"${COMPOSE[@]}" exec -T db sh -c 'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tA' <<'SQL' | tr -d '\r' | sed '/^$/d' | sort -u > "$WORK/used"
select distinct substr(u, length('/uploads/images/') + 1) from (
  select image_url as u from product
  union select url from product_image
  union select image_url from category
) s where u like '/uploads/images/%';
SQL

# every picture on disk that is old enough to be safe
"${COMPOSE[@]}" exec -T api sh -c "find /app/uploads/images -maxdepth 1 -type f -mmin +$MIN_AGE_MINUTES -printf '%f\n'" \
  | tr -d '\r' | sed '/^$/d' | sort -u > "$WORK/files"

# a database that answers with nothing would make every picture look unused: refuse instead of deleting all
if [ ! -s "$WORK/used" ] && [ -s "$WORK/files" ]; then
  echo "refused: the database lists no pictures in use, so nothing is deleted" >&2
  exit 1
fi

comm -23 "$WORK/files" "$WORK/used" > "$WORK/unused"
count=$(wc -l < "$WORK/unused" | tr -d ' ')
echo "pictures in use: $(wc -l < "$WORK/used" | tr -d ' '), on disk (older than ${MIN_AGE_MINUTES} min): $(wc -l < "$WORK/files" | tr -d ' '), unused: $count"
[ "$count" -eq 0 ] && exit 0

if [ "$APPLY" != true ]; then
  sed 's/^/  unused: /' "$WORK/unused" | head -20
  [ "$count" -gt 20 ] && echo "  ... and $((count - 20)) more"
  echo "nothing deleted; run again with --apply to delete them"
  exit 0
fi

# names are generated by the API (hex + extension); refuse anything else before it reaches rm
if grep -qvE '^[0-9a-f]{32}\.(jpg|png|webp)$' "$WORK/unused"; then
  echo "refused: unexpected file names in the list" >&2
  exit 1
fi

"${COMPOSE[@]}" exec -T api sh -c 'cd /app/uploads/images && xargs rm -f --' < "$WORK/unused"
echo "deleted from the site: $count"

if [ -d "$MIRROR" ]; then
  (cd "$MIRROR" && xargs rm -f -- < "$WORK/unused")
  echo "deleted from the backup mirror: $MIRROR"
fi

if [ -n "${BACKUP_REMOTE:-}" ]; then
  rclone delete "${BACKUP_REMOTE%/}/uploads/images" --files-from "$WORK/unused"
  echo "deleted from the off-site copy: ${BACKUP_REMOTE%/}/uploads/images"
fi
